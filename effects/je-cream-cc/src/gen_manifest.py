#!/usr/bin/env python3
"""Turn src/manifest.json into the two C headers the module needs.

  manifest_bytes.h  the manifest as a byte array (what ec_manifest_ptr/len point at)
  param_index.h     #define EC_<ID> <first slot> for every parameter, so the C code indexes the
                    host's flat f64 array by name instead of by a hand-counted offset

Slot widths come from plug-in API v1 (EFFECTCRAFT_WASM_INTERFACE.md §3): slider/angle/checkbox/
popup = 1 slot, point = 2, color = 4. Run from anywhere; paths are relative to this file.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SLOTS = {"slider": 1, "angle": 1, "checkbox": 1, "popup": 1, "point": 2, "color": 4}


def main() -> None:
    man = json.loads((HERE / "manifest.json").read_text())
    params = man["params"]

    seen = set()
    slot = 0
    lines = ["/* Generated by gen_manifest.py from manifest.json - do not edit. */",
             "#ifndef EC_PARAM_INDEX_H", "#define EC_PARAM_INDEX_H", ""]
    for p in params:
        pid = p["id"]
        assert pid not in seen, f"duplicate parameter id {pid}"
        seen.add(pid)
        kind = p["type"]
        assert kind in SLOTS, f"unknown parameter type {kind!r} in {pid}"
        lines.append(f"#define EC_{pid.upper()} {slot} /* {kind} */")
        slot += SLOTS[kind]
    lines += ["", f"#define EC_NPARAMS {slot}", "", "#endif", ""]
    (HERE / "param_index.h").write_text("\n".join(lines))

    raw = json.dumps(man, separators=(",", ":"), ensure_ascii=False).encode()
    body = ",\n  ".join(",".join(str(b) for b in raw[i:i + 20]) for i in range(0, len(raw), 20))
    (HERE / "manifest_bytes.h").write_text(
        "/* Generated by gen_manifest.py from manifest.json - do not edit. */\n"
        "#ifndef EC_MANIFEST_BYTES_H\n#define EC_MANIFEST_BYTES_H\n\n"
        f"#define EC_MANIFEST_LEN {len(raw)}\n\n"
        f"static const unsigned char EC_MANIFEST[{len(raw)}] = {{\n  {body}\n}};\n\n"
        "#endif\n")
    print(f"manifest: {len(raw)} bytes, {len(params)} parameters, {slot} slots")
    assert len(raw) <= 1024 * 1024, "manifest exceeds the 1 MiB limit"
    assert len(params) <= 256, "more than 256 parameters"


if __name__ == "__main__":
    main()
